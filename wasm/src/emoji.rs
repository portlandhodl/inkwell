pub fn lookup(name: &str) -> Option<&'static str> {
    EMOJI.binary_search_by(|(k, _)| k.cmp(&name)).ok().map(|i| EMOJI[i].1)
}

/// Every shortcode, for the editor's autocomplete.
pub fn all() -> &'static [(&'static str, &'static str)] {
    EMOJI
}

/// Replace every known `:shortcode:` in plain text.
pub fn expand(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find(':') {
        out.push_str(&rest[..start]);
        let after = &rest[start + 1..];
        match after.find(':').and_then(|end| lookup(&after[..end]).map(|e| (end, e))) {
            Some((end, e)) => {
                out.push_str(e);
                rest = &after[end + 1..];
            }
            None => {
                out.push(':');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}
